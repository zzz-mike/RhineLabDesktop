import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import * as THREE from 'three';
await mkdir('.tools', {recursive:true});
const output='.tools/check-mac-effects.mjs';
await build({stdin:{contents:'export * from "./src/projected-shadows.ts"; export * from "./src/lightweight-dof.ts";',resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',packages:'external',outfile:output});
try {
 const {projectShadowPoint,SHADOW_FLOOR_Y,ProjectedShadows,LightweightDOF}=await import(new URL('../'+output,import.meta.url));
 const light=new THREE.Vector3(-6,14,-5), p=new THREE.Vector3(2,3,4);
 const a=projectShadowPoint(p,light), b=projectShadowPoint(p.clone().add(new THREE.Vector3(5,0,7)),light);
 assert.equal(a.y,SHADOW_FLOOR_Y);
 assert.ok(b.clone().sub(a).distanceTo(new THREE.Vector3(5,0,7))<1e-10,'horizontal motion translates a cached shadow');
 const high=projectShadowPoint(p.clone().add(new THREE.Vector3(0,2,0)),light);
 assert.ok(high.clone().sub(a).distanceTo(new THREE.Vector3(12/14,0,10/14))<1e-10,'height shifts along fixed light direction');
 const shadow=new ProjectedShadows(new THREE.Box3(new THREE.Vector3(-2.5,0,-.2),new THREE.Vector3(2.5,3.7,.2)),light);
 const source=new THREE.InstancedMesh(new THREE.BoxGeometry(),new THREE.MeshBasicMaterial(),4); source.count=3;
 const model=new THREE.Group();model.position.set(2,4,3);model.rotation.y=.3;
 shadow.sync(source,[model]);
 const array=shadow.group.children[0], front=shadow.group.children[1], matrix=new THREE.Matrix4();front.getMatrixAt(0,matrix);model.updateMatrix();
 assert.equal(array.instanceMatrix,source.instanceMatrix,'reuse the original instance buffer');
 assert.equal(array.count,3); assert.equal(front.count,1);
 assert.ok(matrix.elements.every((v,i)=>Math.abs(v-model.matrix.elements[i])<1e-6),'foreground follows transform');
 assert.equal(array.layers.mask,2,'exclude cosmetic shadows from AO/depth');
 const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera(34,1,5,300);
 camera.layers.enable(1);
 const ao={enabled:true,normalRenderTarget:{depthTexture:new THREE.DepthTexture(100,100)}};
 const dof=new LightweightDOF(scene,camera,()=>ao);dof.lightweight=true;dof.setSize(1120,630);
 const renders=[],oldTarget={label:'before'};
 let currentTarget=oldTarget;
 const renderer={autoClear:true,getRenderTarget:()=>currentTarget,setRenderTarget:v=>currentTarget=v,getClearColor:v=>v.set('#123456'),getClearAlpha:()=>.3,setClearColor:()=>{},clear:()=>{},render:(object)=>renders.push({object,layers:camera.layers.mask})};
 const read=new THREE.WebGLRenderTarget(1120,630),write=read.clone();
 dof.render(renderer,write,read,0,false);
 assert.equal(renders.length,2,'one quarter-size blur draw plus composite');
 assert.ok(renders.every(r=>r.object!==scene),'AO depth reuse must avoid an extra scene draw');
 assert.equal(currentTarget,oldTarget);assert.equal(renderer.autoClear,true);assert.equal(camera.layers.mask,3);
 assert.equal(dof.metrics.width,280);assert.equal(dof.metrics.height,158);
 renders.length=0;ao.enabled=false;dof.render(renderer,write,read,0,false);
 assert.equal(renders.length,3,'AO-off fallback adds only one half-size depth draw');
 assert.equal(renders[0].object,scene);assert.equal(renders[0].layers,1);assert.equal(camera.layers.mask,3);
 assert.equal(scene.overrideMaterial,null);
 // Restoration must also work after a draw fails, so future UI toggles recover.
 renderer.render=()=>{throw Error('simulated context failure');};
 assert.throws(()=>dof.render(renderer,write,read,0,false));
 assert.equal(scene.overrideMaterial,null);assert.equal(camera.layers.mask,3);assert.equal(currentTarget,oldTarget);assert.equal(renderer.autoClear,true);
 dof.dispose();read.dispose();write.dispose();
 const result={passed:true,checks:['parallel-light translation and lift','shared instance buffer','near model transforms','depth-layer exclusion','AO depth reuse','AO-off fallback','quarter-size blur target','renderer state restored after failure']};
 await mkdir('verification/mac-effects',{recursive:true});
 await writeFile('verification/mac-effects/unit-results.json',JSON.stringify(result,null,2));
 console.log('PASS',result.checks.join('; '));
} finally {await rm(output,{force:true});}
